#!/usr/bin/env node
// Writes prototypes/assets/tokens.css from tokens.json, so the prototypes never drift from the tokens.
// Usage: node docs/ux/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const v = (name) => name.replace(/\./g, "-");

function colors(theme) {
  return Object.entries(t.color[theme]).map(([k, val]) => `  --c-${v(k)}: ${val};`).join("\n");
}
function shadows(theme) {
  return Object.entries(t.shadow[theme]).map(([k, val]) => `  --sh-${k}: ${val};`).join("\n");
}
const shared = [];
shared.push(`  --font-sans: ${t.font["family.sans"]};`, `  --font-display: ${t.font["family.display"]};`, `  --font-mono: ${t.font["family.mono"]};`);
for (const [k, s] of Object.entries(t.type)) {
  if (k.startsWith("$")) continue;
  shared.push(`  --t-${k}-size: ${s.size};`, `  --t-${k}-line: ${s.line};`, `  --t-${k}-weight: ${s.weight};`, `  --t-${k}-track: ${s.tracking};`);
}
for (const [k, s] of Object.entries(t.space)) shared.push(`  --s-${k.replace(".", "_")}: ${s};`);
for (const [k, s] of Object.entries(t.radius)) if (!k.startsWith("$")) shared.push(`  --r-${k}: ${s};`);
for (const [k, s] of Object.entries(t.motion.duration)) shared.push(`  --d-${k}: ${s};`);
for (const [k, s] of Object.entries(t.motion.easing)) shared.push(`  --ease-${k}: ${s};`);
for (const [k, s] of Object.entries(t.motion.hold)) shared.push(`  --hold-${k}: ${s};`);
const reduced = Object.entries(t.motion.reduced)
  .filter(([k]) => k.startsWith("duration."))
  .map(([k, s]) => `    --d-${k.split(".")[1]}: ${s};`).join("\n");

const css = `/* Generated by docs/ux/build-tokens.mjs from docs/ux/tokens.json. Do not edit by hand. */
:root {
${shared.join("\n")}
}
:root, :root[data-theme="dark"] {
  color-scheme: dark;
${colors("dark")}
${shadows("dark")}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${colors("light").replace(/^/gm, "  ")}
${shadows("light").replace(/^/gm, "  ")}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${colors("light")}
${shadows("light")}
}
@media (prefers-reduced-motion: reduce) {
  :root {
${reduced}
  }
}
`;
writeFileSync(join(here, "prototypes/assets/tokens.css"), css);
console.log("wrote prototypes/assets/tokens.css");

export type IconName = keyof typeof ICONS;

interface IconProps {
  name: IconName;
  size?: number;
  className?: string;
}

/** Decorative icon. The text next to it (or `aria-label` on the button) carries the meaning. */
export function Icon({ name, size = 16, className }: IconProps) {
  const Glyph = ICONS[name];
  return <Glyph className={cx("icon", className)} size={size} strokeWidth={1.75} aria-hidden="true" focusable="false" />;
}

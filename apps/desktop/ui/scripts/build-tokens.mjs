#!/usr/bin/env node
// Writes src/styles/tokens.css from docs/ux/tokens.json (the single source of the design tokens).
// Usage: node scripts/build-tokens.mjs          write the file
//        node scripts/build-tokens.mjs --check  fail when the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../../../docs/ux/tokens.json");
const target = join(here, "../src/styles/tokens.css");
const t = JSON.parse(readFileSync(source, "utf8"));
const v = (name) => name.replace(/\./g, "-");

const colors = (theme) =>
  Object.entries(t.color[theme]).map(([k, val]) => `  --c-${v(k)}: ${val};`).join("\n");
const shadows = (theme) =>
  Object.entries(t.shadow[theme]).map(([k, val]) => `  --sh-${k}: ${val};`).join("\n");
const indent = (text) => text.replace(/^/gm, "  ");

const shared = [`  --font-sans: ${t.font["family.sans"]};`, `  --font-mono: ${t.font["family.mono"]};`];
for (const [k, s] of Object.entries(t.type)) {
  if (k.startsWith("$")) continue;
  shared.push(
    `  --t-${k}-size: ${s.size};`,
    `  --t-${k}-line: ${s.line};`,
    `  --t-${k}-weight: ${s.weight};`,
    `  --t-${k}-track: ${s.tracking};`,
  );
}
for (const [k, s] of Object.entries(t.space)) shared.push(`  --s-${k.replace(".", "_")}: ${s};`);
for (const [k, s] of Object.entries(t.radius)) if (!k.startsWith("$")) shared.push(`  --r-${k}: ${s};`);
for (const [k, s] of Object.entries(t.motion.duration)) shared.push(`  --d-${k}: ${s};`);
for (const [k, s] of Object.entries(t.motion.easing)) shared.push(`  --ease-${k}: ${s};`);
for (const [k, s] of Object.entries(t.motion.hold)) shared.push(`  --hold-${k}: ${s};`);
const reduced = Object.entries(t.motion.reduced)
  .filter(([k]) => k.startsWith("duration."))
  .map(([k, s]) => `    --d-${k.split(".")[1]}: ${s};`)
  .join("\n");

const css = `/* Generated by scripts/build-tokens.mjs from docs/ux/tokens.json. Do not edit by hand. */
:root {
${shared.join("\n")}
}
:root,
:root[data-theme="dark"] {
  color-scheme: dark;
${colors("dark")}
${shadows("dark")}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${indent(colors("light"))}
${indent(shadows("light"))}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${colors("light")}
${shadows("light")}
}
@media (prefers-reduced-motion: reduce) {
  :root {
${reduced}
  }
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // A missing file counts as out of date.
  }
  if (current !== css) {
    console.error("src/styles/tokens.css is out of date. Run: pnpm tokens");
    process.exit(1);
  }
  console.log("tokens.css is up to date");
} else {
  writeFileSync(target, css);
  console.log("wrote src/styles/tokens.css");
}
